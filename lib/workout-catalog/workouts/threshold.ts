import type { CatalogStep, CatalogWorkout } from '../types.ts';

function warmup(minutes: number, highPct = 78): CatalogStep {
  return {
    kind: 'warmup',
    durationSec: minutes * 60,
    lowPct: 45,
    highPct,
    cue: 'Start with light pressure and let cadence rise as you warm up.',
  };
}

function work(
  minutes: number,
  pct: number,
  cadence: CatalogStep['cadence'],
  cue: string,
): CatalogStep {
  return { kind: 'work', durationSec: minutes * 60, lowPct: pct, highPct: pct, cadence, cue };
}

function easy(minutes: number, pct = 52): CatalogStep {
  return {
    kind: 'recovery',
    durationSec: minutes * 60,
    lowPct: pct,
    highPct: pct,
    cue: 'Soften pedal pressure and let your breathing settle.',
  };
}

function cooldown(minutes: number): CatalogStep {
  return {
    kind: 'cooldown',
    durationSec: minutes * 60,
    lowPct: 40,
    highPct: 55,
    cue: 'Let power fall gradually while keeping the pedals turning.',
  };
}

